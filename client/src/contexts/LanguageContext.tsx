const ruDictionary = { ...ru, ...ruAcceptance, ...ruSmartBoots };
const arDictionary = { ...ar, ...arAcceptance, ...arSmartBoots };

const originalText = new WeakMap<Text, string>();
const originalAttributes = new WeakMap<Element, Map<string, string>>();
const translatedAttributes = ["aria-label", "placeholder", "title", "alt"];
const ignoredSelector = "script, style, svg, textarea, input, option, [data-language-control], [data-no-translate]";

function getBrowserLanguage(): Language {
  const browserLanguages = navigator.languages?.length ? navigator.languages : [navigator.language];
  const preferred = browserLanguages.find((candidate) => /^ru\b/i.test(candidate) || /^ar\b/i.test(candidate));
  if (/^ru\b/i.test(preferred ?? "")) return "ru";
  if (/^ar\b/i.test(preferred ?? "")) return "ar";
  return "en";
}

type AnalyticsTracker = {
  track?: (eventName: string, eventData?: Record<string, string>) => void;
};

function trackLanguageEvent(eventName: string, eventData: Record<string, string>) {
  const tracker = (window as Window & { umami?: AnalyticsTracker }).umami;
  tracker?.track?.(eventName, eventData);
}

function translate(value: string, language: Language) {
  if (language === "en") return value;
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const core = value.trim();
  const dictionary = language === "ru" ? ruDictionary : arDictionary;
  return `${leading}${dictionary[core] ?? core}${trailing}`;
}

function applyTranslations(language: Language) {
  const root = document.body;
  if (!root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const textNodes: Text[] = [];
  let node: Node | null;
  while ((node = walker.nextNode())) textNodes.push(node as Text);

  textNodes.forEach((textNode) => {
    const parent = textNode.parentElement;
    if (!parent || parent.closest(ignoredSelector)) return;
    const source = originalText.get(textNode) ?? textNode.nodeValue ?? "";
    if (!originalText.has(textNode)) originalText.set(textNode, source);
    const next = translate(source, language);
    if (textNode.nodeValue !== next) textNode.nodeValue = next;
  });

  root.querySelectorAll<HTMLElement>("*").forEach((element) => {
    if (element.closest(ignoredSelector)) return;
    translatedAttributes.forEach((attribute) => {
      const current = element.getAttribute(attribute);
      if (current === null) return;
      const saved = originalAttributes.get(element) ?? new Map<string, string>();
      if (!originalAttributes.has(element)) originalAttributes.set(element, saved);
      const source = saved.get(attribute) ?? current;
      saved.set(attribute, source);
      const next = translate(source, language);
      if (current !== next) element.setAttribute(attribute, next);
    });
  });
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const hasTrackedInitialLanguage = useRef(false);
  const [language, setLanguage] = useState<Language>(() => {
    const requested = new URLSearchParams(window.location.search).get("lang");
    if (requested === "en" || requested === "ru" || requested === "ar") return requested;
    const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return stored === "en" || stored === "ru" || stored === "ar" ? stored : getBrowserLanguage();
  });

  const setLanguageAndSync = useCallback((nextLanguage: Language) => {
    setLanguage(nextLanguage);
    const url = new URL(window.location.href);
    url.searchParams.set("lang", nextLanguage);
    window.history.replaceState(window.history.state, "", `${url.pathname}${url.search}${url.hash}`);
    trackLanguageEvent("language_selected", { language: nextLanguage, source: "manual" });
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
    document.documentElement.dataset.language = language;
    localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
    applyTranslations(language);

    const observer = new MutationObserver(() => applyTranslations(language));
    observer.observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: translatedAttributes });
    return () => observer.disconnect();
  }, [language]);

  useEffect(() => {
    if (hasTrackedInitialLanguage.current) return;
    hasTrackedInitialLanguage.current = true;
    trackLanguageEvent("language_context", {
      browser_language: getBrowserLanguage(),
      selected_language: language,
    });
  }, [language]);

  const value = useMemo(() => ({ language, setLanguage: setLanguageAndSync }), [language, setLanguageAndSync]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used within LanguageProvider");
  return context;
}
